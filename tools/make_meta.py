#!/usr/bin/env python3
"""params.json (the MPC build's one parameter list) -> plugin/ParamsMeta.h for the desktop shell."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'params.json')))
def cs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// generated by tools/make_meta.py from tools/params.json: do not edit', '#pragma once', '#include <cstddef>',
       'namespace cc {', 'struct ParamMeta { const char *key, *name; int min, max, def; int nopt; const char *const *opt; int kind; };',
       '// kind: 0 value, 1 momentary, 2 readout/text']
for i, p in enumerate(d['params']):
    if p.get('options'):
        out.append('static const char *const OPT_%d[] = {%s};' % (i, ', '.join(cs(o) for o in p['options'])))
out.append('static const ParamMeta PARAMS[] = {')
for i, p in enumerate(d['params']):
    o = p.get('options')
    kind = 1 if p.get('momentary') else 2 if (p.get('type') == 'readout' or ('min' not in p and not o)) else 0
    mn, mx = (0, len(o) - 1) if o else (p.get('min', 0), p.get('max', 0))
    out.append('    {%s, %s, %d, %d, %d, %d, %s, %d},' % (cs(p['key']), cs(p.get('name', p['key'])), mn, mx, p.get('default', 0),
               len(o) if o else 0, 'OPT_%d' % i if o else 'nullptr', kind))
out += ['};', 'static const int NUM_PARAMS = (int)(sizeof PARAMS / sizeof PARAMS[0]);',
        'inline const ParamMeta *findParam(const char *k) { for (int i = 0; i < NUM_PARAMS; i++) { const char *a = PARAMS[i].key, *b = k; while (*a && *a == *b) { a++; b++; } if (!*a && !*b) return &PARAMS[i]; } return nullptr; }',
        '} // namespace cc', '']
open(os.path.join(here, '..', 'plugin', 'ParamsMeta.h'), 'w').write('\n'.join(out))
print(len(d['params']), 'params')
